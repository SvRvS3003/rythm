assert.equal(await h1.textContent(), 'Admin panel'); console.log('ok second double tap turns it back');
await p.evaluate(() => Object.defineProperty(navigator, 'standalone', { value: true, configurable: true }));
await h1.dblclick(); await p.waitForTimeout(900);
assert.match((await h1.textContent())!, /iPhone ilova: [0-9a-f]{12}/); console.log('ok installed iPhone app shows its version');
await b.close();
