import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { MUTE_ARGS, silence } from './silent.ts';
const BASE = 'http://127.0.0.1:8787', LOGIN = process.argv[2] || 'admin', PASS = process.argv[3] || 'local-dev-pass';
const b = await chromium.launch({ args: MUTE_ARGS });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await silence(ctx);
const p = await ctx.newPage();
await p.addInitScript(() => {
  (window as any).__asked = 0;
  Object.defineProperty(Notification, 'permission', { get: () => 'default' });
  Notification.requestPermission = async () => { (window as any).__asked++; return 'denied'; };
});
await p.goto(BASE);
const asked = () => p.evaluate(() => (window as any).__asked);
await p.mouse.click(5, 5);
assert.equal(await asked(), 0); console.log('ok signed out: nothing is asked');
const r = await p.evaluate(async c => (await fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(c) })).status, { email: LOGIN, password: PASS });
assert.equal(r, 200);
await p.goto(`${BASE}/account`); await p.waitForSelector('.tag');
assert.equal(await asked(), 0, 'no prompt before a tap');
await p.locator('h1').first().click(); await p.waitForTimeout(100);
assert.equal(await asked(), 1); console.log('ok first tap asks for notifications');
await p.locator('h1').first().click(); await p.waitForTimeout(100);
assert.equal(await asked(), 1); console.log('ok asked only once per launch');
await p.evaluate(() => localStorage.setItem('push-off', '1'));
await p.reload(); await p.waitForSelector('.tag');
await p.locator('h1').first().click(); await p.waitForTimeout(100);
assert.equal(await asked(), 0); console.log('ok switched off stays off');
const tag = await p.locator('.panel .tag').first().textContent();
assert.match(tag!, /doimiy/); console.log(`ok admin plan label: ${tag}`);
assert.equal(await p.locator('a[href="/premium"]').count(), 0); console.log('ok admin has no plans link');
await p.goto(`${BASE}/admin`); await p.waitForSelector('h1');
const heading = p.locator('h1', { hasText: 'Admin panel' });
const h1 = p.locator('main h1, h1').first();
await h1.click(); await p.waitForTimeout(600); await h1.click(); await p.waitForTimeout(800);
assert.equal(await h1.textContent(), 'Admin panel'); console.log('ok two slow taps do nothing');
await h1.dblclick();
await p.waitForTimeout(120);
const turns = () => h1.evaluate(e => e.getAnimations().filter(a => a.constructor.name === 'Animation').length);
const turning = await turns();
assert.ok(turning > 0, 'title animates'); console.log('ok title turns over');
await p.waitForTimeout(900);
assert.match((await h1.textContent())!, /Sayt: [0-9a-f]{12}.*Oxirgi APK/); console.log(`ok version on the back: ${await h1.textContent()}`);
