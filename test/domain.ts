import { readFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { MUTE_ARGS, silence } from './silent.ts';
const [ORIGIN, SHOT, IP] = process.argv.slice(2);
const host = new URL(ORIGIN).hostname;
const v = Object.fromEntries(readFileSync('.prod.vars', 'utf8').split('\n').filter(l => l.includes('=')).map(l => { const i = l.indexOf('='); return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, '')]; }));
const b = await chromium.launch({ args: [...MUTE_ARGS, ...(IP ? [`--host-resolver-rules=MAP ${host} ${IP}`] : [])] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await silence(ctx);
const p = await ctx.newPage();
const bad: string[] = [];
p.on('pageerror', e => bad.push(`error: ${e.message}`));
p.on('response', r => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().slice(0, 90)}`); });
p.on('requestfailed', r => bad.push(`failed ${r.url().slice(0, 90)} ${r.failure()?.errorText}`));
await p.goto(ORIGIN);
const anon = (await p.locator('body').innerText()).slice(0, 80).replace(/\n/g, ' ');
const login = await p.evaluate(async c => (await fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(c) })).status, { email: v.ADMIN_LOGIN, password: v.ADMIN_PASSWORD });
await p.goto(ORIGIN); await p.waitForTimeout(5000);
const home = await p.evaluate(async () => { const d = await (await fetch('/api/home')).json(); return { fresh: d.fresh?.length, popular: d.popular?.length, titles: d.fresh?.map((t: any) => t.title) }; });
console.log({ anon, login, home, cards: await p.locator('.card').count(), text: (await p.locator('main, #root').first().innerText()).slice(0, 160).replace(/\n/g, ' | ') });
console.log('problems:', bad.slice(0, 8));
await p.screenshot({ path: SHOT });
await b.close();
