import assert from 'node:assert/strict';
import { chromium, webkit } from 'playwright';
import { MUTE_ARGS, silence } from './silent.ts';
const BASE = 'http://127.0.0.1:8787';
const IOS = 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1';
const onWebkit = process.argv[3] === 'webkit';
const b = onWebkit ? await webkit.launch() : await chromium.launch({ args: [...MUTE_ARGS, '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, ...(onWebkit ? { userAgent: IOS } : {}) });
await silence(ctx);
const p = await ctx.newPage();
await p.addInitScript(() => { const o = HTMLMediaElement.prototype.play; HTMLMediaElement.prototype.play = function () { (window as unknown as { __a: HTMLMediaElement }).__a = this; return o.call(this); }; });
const errors: string[] = []; p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE);
await p.evaluate(() => fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'local-dev-pass' }) }));
await p.goto(BASE); await p.waitForSelector('.stage-go .btn');
const box = () => p.evaluate(() => { const r = document.querySelector('.stage-gl')!.getBoundingClientRect(); return { top: Math.round(r.top), left: Math.round(r.left), w: Math.round(r.width), h: Math.round(r.height), bg: document.querySelector('.main')!.scrollWidth <= innerWidth }; });
const start = await box();
assert.equal(start.top, 0); assert.equal(start.left, 0); assert.equal(start.w, 390); assert.ok(start.bg, 'no sideways scroll');
await p.evaluate(() => { document.querySelector('.main')!.scrollTop = 700; }); await p.waitForTimeout(200);
const down = await box();
assert.equal(down.top, 0, 'landscape must stay in view while scrolling'); console.log('ok landscape stays behind the page');
assert.ok(await p.evaluate(() => Number((document.querySelector('.stage-gl') as HTMLElement).style.opacity) < 0.6)); console.log('ok it steps back further down');
await p.screenshot({ path: process.argv[2] ? `${process.argv[2]}/stage-down.png` : '/tmp/stage-down.png' });
await p.evaluate(() => { document.querySelector('.main')!.scrollTop = 0; });
const lead = await p.locator('.stage-lead h1').textContent();
await p.locator('.stage-go .btn').click(); await p.waitForSelector('.player.show'); await p.waitForTimeout(2500);
const state = () => p.evaluate(() => ({ eyebrow: document.querySelector('.eyebrow')!.textContent, title: document.querySelector('.stage-lead h1')!.textContent, btn: document.querySelector('.stage-go .btn')!.textContent, mini: document.querySelector('.player .info .clip')!.textContent }));
const on = await state();
assert.equal(on.title, on.mini, 'stage and player must show one song'); assert.equal(on.eyebrow, 'Hozir chalinmoqda'); assert.equal(on.btn, 'Pauza'); console.log(`ok playing "${on.title}" (was "${lead}")`);
await p.locator('.card').nth(2).click({ force: true }); await p.waitForTimeout(2500);
const other = await state();
assert.equal(other.title, other.mini, 'a song picked below takes over the stage'); console.log(`ok song picked below takes over: "${other.title}"`);
if (process.argv[2]) await p.screenshot({ path: `${process.argv[2]}/stage-play.png` });

const songs = p.locator('.tr .hit');
await songs.nth(0).dispatchEvent('click'); await p.waitForTimeout(2500);
const audioState = () => p.evaluate(() => { const a = (window as unknown as { __a: HTMLMediaElement }).__a; return { paused: a.paused, src: a.src }; });
const firstSrc = (await audioState()).src;

const playLink = (mode: string) => p.evaluate(m => { const w = window as unknown as { __f?: typeof fetch }; const real = w.__f ??= fetch; window.fetch = (u, o) => String(u) !== '/api/play' || m === 'open' ? real(u, o) : m === 'slow' ? new Promise(f => setTimeout(f, 5000)).then(() => real(u, o)) : Promise.resolve(new Response('{"error":"sinov"}', { status: 500 })); }, mode);
await playLink('slow');
await songs.nth(1).dispatchEvent('click'); await p.waitForTimeout(500);
const wait = await state(), held = await audioState();
assert.equal(wait.title, await songs.nth(1).locator('.t').textContent()); assert.equal(wait.title, wait.mini);
assert.equal(wait.eyebrow, 'Yuklanmoqda'); assert.equal(held.src, firstSrc); assert.equal(held.paused, true, 'the old song must be silent under the new title');
assert.equal(await p.locator('.player [data-cur]').first().textContent(), '0:00', 'no old seconds under the new title');
console.log('ok while a song is on its way, nothing of the old one shows or sounds');
await p.waitForTimeout(7500);
const landed = await audioState(), after = await state();
assert.notEqual(landed.src, firstSrc); assert.equal(after.eyebrow, 'Hozir chalinmoqda'); console.log('ok the new song takes over with sound');

await playLink('refuse');
await songs.nth(2).dispatchEvent('click'); await p.waitForTimeout(500);
const back = await state(), kept = await audioState();
assert.equal(back.title, after.title, 'title returns to the song still sounding'); assert.equal(back.mini, after.title); assert.equal(kept.src, landed.src); assert.equal(kept.paused, false, 'the old song plays on'); console.log('ok a refused switch returns to the sounding song');
await playLink('open');
await p.locator('.stage-go .btn').click(); await p.waitForTimeout(500);
const off = await state();
assert.equal(off.eyebrow, 'To\'xtatilgan'); assert.equal(off.btn, 'Davom etish'); console.log('ok the stage button pauses the same song');
await p.locator('.stage-go .btn').click(); await p.waitForTimeout(1000);
assert.equal((await state()).btn, 'Pauza'); console.log('ok and resumes it');
await p.locator('.stage-lead h1').click(); await p.waitForSelector('.now.show'); console.log('ok the title opens the player');
assert.deepEqual(errors, []);
await b.close();
