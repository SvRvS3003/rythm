import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { silence } from './silent.ts';
const BASE = 'http://127.0.0.1:8787', OUT = process.argv[2];

const wav = join(OUT, 'Topish Sinovi.wav'), mic = join(OUT, 'mic.wav');
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'lavfi', '-i', "aevalsrc='0.25*sin(2*PI*(220+55*mod(floor(t/1.3)\\,7))*t)+0.2*sin(2*PI*(660+110*mod(floor(t/0.7)\\,5))*t)+0.5*exp(-18*mod(t\\,0.5))*sin(2*PI*70*t)+0.15*exp(-30*mod(t+0.25\\,0.5))*sin(2*PI*5000*t)':d=60:s=48000", '-ac', '2', '-c:a', 'pcm_s16le', wav]);

execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-ss', '20', '-i', wav, '-af', 'aecho=0.8:0.7:60:0.3,highpass=f=250,lowpass=f=5000,volume=0.5', '-c:a', 'pcm_s16le', mic]);
const b = await chromium.launch({ args: ['--mute-audio', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', `--use-file-for-fake-audio-capture=${mic}`, '--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block', permissions: ['microphone'] });
await silence(ctx);
const p = await ctx.newPage();
const errors: string[] = []; p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE);
await p.evaluate(() => fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'local-dev-pass' }) }));
await p.goto(`${BASE}/admin/upload`); await p.waitForSelector('input[type=file][multiple]');
await p.locator('input[type=file][multiple]').setInputFiles(wav);
await p.locator('.preview .verdict.ok, .preview .verdict.similar').waitFor({ timeout: 60000 });
await p.getByRole('textbox', { name: "Qo'shiq nomi" }).fill('Topish Sinovi');
await p.getByRole('button', { name: 'Yuklash', exact: true }).click();
await p.waitForURL(u => u.pathname === '/', { timeout: 120000 });
await p.goto(`${BASE}/admin/find`); await p.waitForSelector('[data-find]');
await p.locator('[data-find]').click();
const found = p.locator('[data-found]');
await found.waitFor({ timeout: 40000 });
const text = await found.textContent();
console.log('heard:', text, await found.getAttribute('data-found'));
assert.match(String(text), /Topish Sinovi/);
assert.equal(await found.getAttribute('data-found'), 'found');
await p.getByRole('button', { name: 'Ochish' }).click();
await p.waitForFunction(() => document.querySelector('.player .info:not(.ghost) .clip')?.textContent === 'Topish Sinovi', undefined, { timeout: 15000 });
console.log('ok the song is recognised through a microphone and opens');
const del = await p.evaluate(async () => { const { tracks } = await (await fetch('/api/admin/tracks')).json(); const t = tracks.find((x: { title: string }) => x.title === 'Topish Sinovi'); return (await fetch(`/api/admin/tracks/${t.id}`, { method: 'DELETE' })).status; });
assert.equal(del, 200);
assert.deepEqual(errors, []);
await b.close();

const nb = await chromium.launch({ args: ['--mute-audio', '--deny-permission-prompts'] });
const nctx = await nb.newContext({ serviceWorkers: 'block' });
const n = await nctx.newPage();
await n.goto(BASE);
await n.evaluate(() => fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'local-dev-pass' }) }));
await n.goto(`${BASE}/admin/find`); await n.waitForSelector('[data-find]');
await n.locator('[data-find]').click();
await n.getByText(/Mikrofon/).first().waitFor({ timeout: 10000 });
console.log('refused:', await n.locator('.panel p').first().textContent());
await nb.close();
