import assert from 'node:assert/strict';
import { chromium, webkit } from 'playwright';
import { MUTE_ARGS, silence } from './silent.ts';
const BASE = 'http://127.0.0.1:8787';
const b = process.argv[2] === 'webkit' ? await webkit.launch() : await chromium.launch({ args: MUTE_ARGS });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
await silence(ctx);
const p = await ctx.newPage();
const errors: string[] = []; p.on('pageerror', e => errors.push(e.message));
let navigations = 0; p.on('framenavigated', f => { if (f === p.mainFrame()) navigations++; });
await p.goto(BASE);
await p.evaluate(() => fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'local-dev-pass' }) }));
await p.goto(BASE); await p.waitForSelector('.shelf .card[data-track]'); await p.waitForTimeout(1500);

const SECRET = Date.now();
const lctx = await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
await silence(lctx);
const signup = await lctx.request.post(`${BASE}/api/auth/register`, { data: { name: 'Jonli', email: `jonli${SECRET}@example.com`, password: 'jonli-sinov-1234' } });
assert.ok(signup.ok(), `signup ${signup.status()}`);
const l = await lctx.newPage();
await l.goto(BASE); await l.waitForSelector('.shelf .card[data-track]'); await l.waitForTimeout(1500);
const opened = navigations;
const newest = await p.locator('.shelf .card[data-track]').first().getAttribute('data-track');
const title = await p.locator('.shelf .card[data-track]').first().locator('.t').textContent();

const other = await ctx.request.patch(`${BASE}/api/admin/tracks/${newest}`, { data: { published: false } });
assert.ok(other.ok(), `unpublish ${other.status()}`);
await p.waitForFunction(id => !document.querySelector(`.shelf .card[data-track="${id}"]`), newest, { timeout: 40000 });
console.log(`ok "${title}" left the open page by itself`);
await l.waitForFunction(id => !document.querySelector(`.shelf .card[data-track="${id}"]`), newest, { timeout: 75000 });
console.log('ok and left a listener\'s open page too');
const back = await ctx.request.patch(`${BASE}/api/admin/tracks/${newest}`, { data: { published: true } });
assert.ok(back.ok());
await p.waitForSelector(`.shelf .card[data-track="${newest}"]`, { timeout: 40000 });
console.log(`ok and came back by itself`);
await l.waitForSelector(`.shelf .card[data-track="${newest}"]`, { timeout: 75000 });
console.log('ok and came back for the listener');
assert.equal(navigations, opened, 'the page was never reloaded');
assert.deepEqual(errors, []);
await b.close();
