import assert from 'node:assert/strict';
import { chromium, webkit } from 'playwright';
import { MUTE_ARGS, silence } from './silent.ts';
const BASE = 'http://127.0.0.1:8787';
const onWebkit = process.argv[3] === 'webkit';
const b = onWebkit ? await webkit.launch() : await chromium.launch({ args: [...MUTE_ARGS, '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
await silence(ctx);
const p = await ctx.newPage();
const errors: string[] = []; p.on('pageerror', e => errors.push(e.message));

await p.addInitScript(() => { const play = HTMLMediaElement.prototype.play; HTMLMediaElement.prototype.play = function () { (window as unknown as { __a: HTMLMediaElement }).__a = this; return play.call(this); }; });

await p.addInitScript(() => {
  const w = window as unknown as { __seen: string[] }; w.__seen = [];
  const names = /^(flip|swipe)-(next|prev)(-out)?$/;
  new MutationObserver(list => { for (const m of list) for (const n of m.addedNodes) if (n instanceof HTMLElement) for (const e of [n, ...n.querySelectorAll('*')]) for (const c of e.classList) if (names.test(c)) w.__seen.push(c); }).observe(document, { childList: true, subtree: true });
});
const seen = () => p.evaluate(() => { const w = window as unknown as { __seen: string[] }; const v = [...new Set(w.__seen)].sort(); w.__seen = []; return v; });
await p.goto(BASE);
await p.evaluate(() => fetch('/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'local-dev-pass' }) }));
await p.goto(BASE); await p.waitForSelector('.tr .hit');
await p.locator('.tr .hit').first().dispatchEvent('click'); await p.waitForSelector('.player.show'); await p.waitForTimeout(1500);
await seen();
const press = async (label: string, where: string) => { await p.locator(`${where} button[aria-label="${label}"]`).first().dispatchEvent('click'); await p.waitForTimeout(1100); return seen(); };

await p.setViewportSize({ width: 1280, height: 800 }); await p.waitForTimeout(300);
assert.deepEqual(await press('Keyingi', '.player'), ['flip-next', 'flip-next-out']); console.log('ok mini player turns upward on next');
assert.deepEqual(await press('Oldingi', '.player'), ['flip-prev', 'flip-prev-out']); console.log('ok mini player turns downward on back');
await p.setViewportSize({ width: 390, height: 844 });
await p.locator('.player .info:not(.ghost)').first().click(); await p.waitForSelector('.now.show'); await p.waitForTimeout(600); await seen();
const water = await p.evaluate(() => { const c = document.querySelector('.now .water-seek .tide')!.getBoundingClientRect(), n = document.querySelector('.now-in')!.getBoundingClientRect(); return { h: c.height, w: c.width, frame: n.width }; });
assert.equal(water.h, 12, 'a line, a little thicker'); assert.ok(water.w <= water.frame && water.w > 200); console.log('ok the seek line is water, 12 px thick');
const keep = await p.evaluateHandle(() => document.querySelector('.now .playbtn.big'));
assert.deepEqual((await press('Keyingi', '.now')).filter(c => c.startsWith('swipe')), ['swipe-next', 'swipe-next-out']); console.log('ok full player slides right to left on next');
assert.deepEqual((await press('Oldingi', '.now')).filter(c => c.startsWith('swipe')), ['swipe-prev', 'swipe-prev-out']); console.log('ok full player slides left to right on back');
assert.equal(await p.evaluate(() => document.querySelectorAll('.ghost').length), 0, 'copies are gone afterwards');
const before = await p.evaluateHandle(() => document.querySelector('.now .playbtn.big'));
await before.evaluate((e: Element) => (e as HTMLElement).click()); await p.waitForTimeout(500);
assert.equal(await p.evaluate(([x]) => x === document.querySelector('.now .playbtn.big'), [before]), true, 'pausing must not rebuild the player'); console.log('ok pausing does not rebuild the full player');
await keep.dispose();
await before.evaluate((e: Element) => (e as HTMLElement).click()); await p.waitForTimeout(1200);
if (process.argv[2]) await p.screenshot({ path: `${process.argv[2]}/now-water.png` });

const seek = p.locator('.now [data-seek]');
await seek.evaluate((e: HTMLInputElement) => { e.value = String(Number(e.max) * 0.6); e.dispatchEvent(new Event('input', { bubbles: true })); e.dispatchEvent(new Event('change', { bubbles: true })); });
await p.waitForTimeout(900);
const at = await p.locator('.now [data-cur]').textContent(), total = await p.locator('.now [data-dur]').textContent();
const secs = (t: string | null) => { const [m, s] = String(t).split(':').map(Number); return m * 60 + s; };
assert.ok(secs(at) / secs(total) > 0.5, `seek moved to ${at} of ${total}`); console.log('ok seeking still works');
if (process.argv[2]) await p.screenshot({ path: `${process.argv[2]}/now-water2.png` });

const animated = () => p.evaluate(() => document.getAnimations().map(x => (x.effect as KeyframeEffect).target).filter(Boolean).map(e => (e as Element).tagName.toLowerCase()));
const big = p.locator('.now .playbtn.big');
await big.dispatchEvent('click'); await p.waitForTimeout(40);
assert.ok((await animated()).includes('svg'), 'the play icon must turn in'); console.log('ok the play icon turns in');
const icon0 = await big.evaluateHandle(e => e.firstElementChild);
await p.evaluate(() => dispatchEvent(new Event('noop'))); await p.waitForTimeout(400);
await big.dispatchEvent('click'); await p.waitForTimeout(600);
const icon1 = await big.evaluateHandle(e => e.firstElementChild);
await p.waitForTimeout(1500);
assert.equal(await p.evaluate(([x]) => x === document.querySelector('.now .playbtn.big')!.firstElementChild, [icon1]), true, 'syncs must not redraw a settled icon'); console.log('ok a settled icon stays untouched'); await icon0.dispose();
await p.locator('.now button[aria-label="Yopish"]').click(); await p.waitForTimeout(500);
assert.equal(await p.evaluate(() => document.querySelector('.now')!.classList.contains('show')), false);
await p.locator('.player > .playbtn').dispatchEvent('click'); await p.waitForTimeout(40);
const ease = await p.evaluate(() => document.getAnimations().filter(x => (x.effect as KeyframeEffect).target === document.querySelector('.eyebrow')).length);
assert.ok(ease > 0, 'changed text must ease in'); console.log('ok changed text eases in');
await p.locator('.player .info:not(.ghost)').first().click(); await p.waitForTimeout(60);
assert.ok(await p.evaluate(() => document.querySelector('.now')!.classList.contains('opening') && document.getAnimations().length > 2), 'opening is staged'); console.log('ok opening the big player is staged');
await p.waitForTimeout(800);
assert.equal(await p.evaluate(() => document.querySelector('.now')!.classList.contains('opening')), false);
await p.locator('.now button[aria-label="Pleylistga qo\'shish"]').click(); await p.waitForSelector('.sheet');
await p.keyboard.press('Escape'); await p.waitForTimeout(60);
assert.ok(await p.evaluate(() => { const s = document.querySelector<HTMLElement>('.scrim'); return !!s && s.getAnimations().length > 0; }), 'a sheet fades away'); await p.waitForSelector('.scrim', { state: 'detached', timeout: 3000 });
assert.equal(await p.locator('.scrim').count(), 0); console.log('ok a sheet fades away, then is gone');

await p.goto(BASE); await p.waitForSelector('.tr .hit');
await p.locator('.tr .hit').first().dispatchEvent('click'); await p.waitForSelector('.player.show'); await p.waitForTimeout(1500);
const sounding = () => p.evaluate(() => { const a = (window as unknown as { __a: HTMLMediaElement }).__a; return !a.paused; });
assert.ok(await sounding(), 'the first song plays');
let release: () => void = () => {};
await p.route('**/api/play', r => new Promise<void>(go => { release = () => { go(); r.continue().catch(() => {}); }; }));
await p.setViewportSize({ width: 1280, height: 800 }); await p.waitForTimeout(300);
await p.locator('.tr .hit').nth(3).dispatchEvent('click'); await p.waitForTimeout(400);
assert.ok(await p.evaluate(() => document.querySelector('.player')!.textContent!.length > 0));
await p.locator('.player .playbtn').first().dispatchEvent('click'); await p.waitForTimeout(1500);
assert.equal(await sounding(), false, 'pause during a switch must silence, not resume the old song');
release(); await p.waitForTimeout(1500);
assert.equal(await sounding(), false, 'a late answer for the abandoned song must not start it');
await p.unroute('**/api/play'); console.log('ok pause during a song change gives silence');
assert.deepEqual(errors, []);
await b.close();
